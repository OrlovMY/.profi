#!/usr/bin/env bash
# Наблюдатель за входящей почтой. Один скрипт для ОБЕИХ сторон.
#
#   исполнитель проекта MDMy:  bash watch-mail.sh от-PE-01.md
#   PE-01 / PQ-01 / HR-D:      bash watch-mail.sh от-MDMy.md
#
# Запускать через Monitor с persistent: true.
#
# ═══════════════════════════════════════════════════════════════════════════
# ПОЧЕМУ ЗДЕСЬ НЕТ НИ МОДЕЛИ, НИ GIT
# ═══════════════════════════════════════════════════════════════════════════
#
# МОДЕЛИ НЕТ. Опрос — цикл в оболочке; Monitor превращает каждую строку stdout
# в уведомление. Агент-опрашиватель (хоть на самой дешёвой модели) платил бы
# токенами за каждый цикл; здесь платить не за что. Это не «сэкономили», это
# другой класс: ноль вместо малого.
#
# GIT НЕТ. Обе стороны работают на одной машине, значит файл на диске и есть
# транспорт: запись видна мгновенно. Git как транспорт добавлял бы задержку
# опроса удалённой ветки и засорял свод коммитами живой переписки.
#
# ЦЕНА ЭТОГО ВЫБОРА, названная прямо: временный каталог не версионируется и не
# переживёт очистку temp. Переписка здесь — расходный материал. Всё, что должно
# жить, переносится в `.profi` отдельным осознанным ходом (разбор, стандарт,
# запись памяти). Обнаружение канала — тоже в `.profi`: сессия, начавшаяся с
# нуля, читает свод, а не temp, и без указателя там канал не найдёт.
#
# ═══════════════════════════════════════════════════════════════════════════
#
# Каждая строка stdout — одно уведомление, поэтому на письмо выводится ровно
# ОДНА строка: тема плюс пометки из шапки. Письмо читается по факту.

set -uo pipefail

MAILBOX="${1:-}"
if [ -z "$MAILBOX" ]; then
    echo "СТОП: не задан почтовый ящик. Пример: $0 от-PE-01.md" >&2
    exit 2
fi

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FILE="$DIR/$MAILBOX"
INTERVAL="${MAIL_POLL_SECONDS:-2}"

# Отсутствие ящика — громкий отказ, а не молчание: наблюдатель, молчащий по
# причине, не имеющей отношения к отсутствию писем, ничем не лучше
# отсутствующего.
if [ ! -f "$FILE" ]; then
    echo "СТОП: нет файла $FILE — опечатка в имени ящика?" >&2
    exit 2
fi

# Отпечаток СОДЕРЖИМОГО, а не времени правки: перезапись тем же текстом письмом
# не является, а mtime меняется от чего угодно, включая копирование.
snap()  { md5sum < "$FILE" | cut -d' ' -f1; }
count() { grep -c '^## 20' "$FILE" 2>/dev/null || echo 0; }

last_subject() {
    awk '
        /^## 20/ { subj = $0; wait = ""; urg = "" }
        /^ЖДУ ОТВЕТА:/ { wait = $0 }
        /^СРОЧНОСТЬ:/  { urg = $0 }
        END {
            gsub(/^## /, "", subj)
            gsub(/^ЖДУ ОТВЕТА: /, "", wait)
            gsub(/^СРОЧНОСТЬ: /, "", urg)
            if (subj == "") { print "(шапка не разобрана)" }
            else { printf "%s | ответ: %s | срочность: %s\n", subj, wait, urg }
        }' "$FILE"
}

# Базовая линия ставится МОЛЧА: иначе каждый запуск сообщал бы о письме,
# которое давно прочитано.
prev="$(snap)"
prev_count="$(count)"
echo "наблюдатель за $MAILBOX запущен; писем в ящике: $prev_count; опрос раз в ${INTERVAL}с, модели не расходует"

while true; do
    sleep "$INTERVAL"
    cur="$(snap)"
    [ "$cur" = "$prev" ] && continue
    cur_count="$(count)"
    if [ "$cur_count" -gt "$prev_count" ]; then
        echo "НОВОЕ ПИСЬМО в $MAILBOX: $(last_subject)"
    else
        # Протокол запрещает править прежние записи: молчаливая правка задним
        # числом ломает единственное преимущество канала над разговором —
        # возможность увидеть, кто что знал и когда.
        echo "ИЗМЕНЕНО БЕЗ НОВОГО ПИСЬМА в $MAILBOX — правка прежней записи, протокол это запрещает"
    fi
    prev="$cur"
    prev_count="$cur_count"
done
